// The hook writer is tested against temporary directories only; no test
// touches the hooks of this repository.

func readHook(t *testing.T, dir, name string) string {
	t.Helper()

	content, err := os.ReadFile(filepath.Join(dir, name)) //nolint:gosec // G304: the test's own file
	if err != nil {
		t.Fatalf("read %s: %v", name, err)
	}

	return string(content)
}

func TestInstallHooksWritesManagedHooks(t *testing.T) {
	t.Parallel()

	dir := filepath.Join(t.TempDir(), "hooks")
	out := &bytes.Buffer{}

	if err := installHooks(out, dir, gitHooks, installOptions{command: devEserCommand}); err != nil { //nolint:exhaustruct
		t.Fatal(err)
	}

	want := map[string]string{
		"pre-commit": "go run ./cmd/eser workflows run -e precommit\n",
		"commit-msg": "go run ./cmd/eser workflows run -e commitmsg -- \"$1\"\n",
		"pre-push":   "go run ./cmd/eser workflows run -e prepush\n",
	}

	for name, command := range want {
		content := readHook(t, dir, name)
		if !strings.HasPrefix(content, "#!/bin/sh\n"+hookMarker) || !strings.HasSuffix(content, "\n"+command) {
			t.Errorf("%s:\n%s", name, content)
		}

		info, err := os.Stat(filepath.Join(dir, name))
		if err != nil || info.Mode().Perm()&0o111 == 0 {
			t.Errorf("%s is not executable: %v", name, err)
		}
	}

	if !strings.Contains(out.String(), "Done: 3 installed, 0 updated, 0 skipped") {
		t.Errorf("install output:\n%s", out)
	}
}

func TestInstallHooksKeepsUserHooks(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	userHook := "#!/bin/sh\necho mine\n"

	if err := os.WriteFile(filepath.Join(dir, "pre-commit"), []byte(userHook), 0o755); err != nil { //nolint:gosec // G306: a hook
		t.Fatal(err)
	}

	// A hook the TypeScript install wrote carries the same marker.
	tsHook := "#!/bin/sh\n# @eser managed hook — generated by `eser codebase install`\n\npnpm cli workflows run -e prepush\n"
	if err := os.WriteFile(filepath.Join(dir, "pre-push"), []byte(tsHook), 0o600); err != nil {
		t.Fatal(err)
	}

	out := &bytes.Buffer{}
	if err := installHooks(out, dir, gitHooks, installOptions{command: "eser"}); err != nil { //nolint:exhaustruct
		t.Fatal(err)
	}

	if readHook(t, dir, "pre-commit") != userHook {
		t.Error("install replaced a user hook without --force")
	}

	if got := readHook(t, dir, "pre-push"); !strings.HasSuffix(got, "\neser workflows run -e prepush\n") {
		t.Errorf("install should update the TypeScript-managed hook:\n%s", got)
	}

	if !strings.Contains(out.String(), "Done: 1 installed, 1 updated, 1 skipped") {
		t.Errorf("install output:\n%s", out)
	}

	// --dry-run writes nothing; --force replaces the user hook.
	if err := installHooks(&bytes.Buffer{}, dir, gitHooks, installOptions{command: "eser", force: true, dryRun: true}); err != nil {
		t.Fatal(err)
	}

	if readHook(t, dir, "pre-commit") != userHook {
		t.Error("--dry-run changed a hook")
	}

	if err := installHooks(&bytes.Buffer{}, dir, gitHooks, installOptions{command: "eser", force: true}); err != nil { //nolint:exhaustruct
		t.Fatal(err)
	}

	if !strings.Contains(readHook(t, dir, "pre-commit"), hookMarker) {
		t.Error("--force should replace the user hook")
	}

	// uninstall removes only the managed hooks.
	if err := os.WriteFile(filepath.Join(dir, "pre-commit"), []byte(userHook), 0o600); err != nil {
		t.Fatal(err)
	}

	if err := uninstallHooks(&bytes.Buffer{}, dir); err != nil {
		t.Fatal(err)
	}

	if !fileExists(filepath.Join(dir, "pre-commit")) || fileExists(filepath.Join(dir, "commit-msg")) || fileExists(filepath.Join(dir, "pre-push")) {
		t.Error("uninstall should remove the managed hooks and keep the user hook")
	}
}

func TestHookCommand(t *testing.T) {
	t.Parallel()

	if got := hookCommand(filepath.Join("..", "..")); got != devEserCommand {
		t.Errorf("in eser/stack the hooks should run %q, got %q", devEserCommand, got)
	}

	other := t.TempDir()
	if err := os.WriteFile(filepath.Join(other, "go.mod"), []byte("module example.com/app\n"), 0o600); err != nil {
		t.Fatal(err)
	}

	if got := hookCommand(other); got != "eser" {
		t.Errorf("elsewhere the hooks should run eser, got %q", got)
	}
}

// TestCodebaseInstallInATemporaryRepository runs `eser codebase install` in
// a fresh git repository whose core.hooksPath points into it.
func TestCodebaseInstallInATemporaryRepository(t *testing.T) {
	t.Parallel()

	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("needs git")
	}

	e := testEnv(t)
	writeManifest(t, e.cwd, gateManifest)

	hooks := filepath.Join(e.cwd, "local-hooks")
	for _, args := range [][]string{{"init", "-q"}, {"config", "core.hooksPath", hooks}} {
		cmd := exec.Command("git", args...) //nolint:noctx // a short git call in a test
		cmd.Dir = e.cwd

		if out, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("git %v: %v\n%s", args, err, out)
		}
	}

	if code := run(context.Background(), e, []string{"codebase", "install"}); code != 0 {
		t.Fatalf("codebase install: exit %d:\n%s", code, output(e))
	}

	if got := readHook(t, hooks, "commit-msg"); !strings.HasSuffix(got, "\neser workflows run -e commitmsg -- \"$1\"\n") {
		t.Errorf("commit-msg:\n%s", got)
	}

	if fileExists(filepath.Join(hooks, "pre-push")) {
		t.Error("the manifest has no prepush workflow, so no pre-push hook should be written")
	}

	e.stdout = &bytes.Buffer{}
	if code := run(context.Background(), e, []string{"codebase", "status"}); code != 0 ||
		!strings.Contains(output(e), "managed (eser)") {
		t.Errorf("codebase status: exit %d:\n%s", code, output(e))
	}

	if code := run(context.Background(), e, []string{"codebase", "uninstall"}); code != 0 || fileExists(filepath.Join(hooks, "pre-commit")) {
		t.Errorf("codebase uninstall: exit %d:\n%s", code, output(e))
	}
}
