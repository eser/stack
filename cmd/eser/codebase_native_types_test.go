// nativeTypesEnv is a workspace with the packages that own the native functions
// (the validators, and workflow-steps), and the path of the first one's module.
func nativeTypesEnv(t *testing.T) (*env, string) {
	t.Helper()

	e := testEnv(t)

	for _, owner := range []string{"codebase", "workflows"} {
		if err := os.MkdirAll(filepath.Join(e.cwd, "pkg", "@eserstack", owner), 0o750); err != nil {
			t.Fatal(err)
		}
	}

	return e, filepath.Join(e.cwd, "pkg", "@eserstack", "codebase", "native-functions.ts")
}

func TestNativeTypesWritesTheModuleIntoTheOwnerPackage(t *testing.T) {
	t.Parallel()

	e, path := nativeTypesEnv(t)

	if code := run(context.Background(), e, []string{"codebase", "native-types"}); code != 0 {
		t.Fatalf("native-types: exit %d: %s", code, e.stderr)
	}

	written, err := os.ReadFile(path) //nolint:gosec // G304: a file of the test's temporary workspace
	if err != nil {
		t.Fatalf("the module was not written: %v", err)
	}

	for _, want := range []string{
		"// Generated by `go run ./cmd/eser codebase native-types`",
		"export type ValidateEofInput = {",
		"export type ValidateEofOutput = ",
		"export type NativeFunctions = {",
	} {
		if !strings.Contains(string(written), want) {
			t.Errorf("the module lacks %q", want)
		}
	}

	if out := e.stdout.(*bytes.Buffer).String(); !strings.Contains(out, "wrote "+path) { //nolint:forcetypeassert
		t.Errorf("stdout = %q, want it to name the file it wrote", out)
	}
}

func TestNativeTypesCheckPassesOnAFreshFileAndWritesNothing(t *testing.T) {
	t.Parallel()

	e, path := nativeTypesEnv(t)

	if code := run(context.Background(), e, []string{"codebase", "native-types"}); code != 0 {
		t.Fatalf("native-types: exit %d: %s", code, e.stderr)
	}

	before, err := os.Stat(path)
	if err != nil {
		t.Fatal(err)
	}

	e.stdout.(*bytes.Buffer).Reset() //nolint:forcetypeassert

	if code := run(context.Background(), e, []string{"codebase", "native-types", "--check"}); code != 0 {
		t.Fatalf("native-types --check on a fresh file: exit %d: %s", code, e.stderr)
	}

	after, err := os.Stat(path)
	if err != nil {
		t.Fatal(err)
	}

	if !after.ModTime().Equal(before.ModTime()) {
		t.Error("--check wrote the file")
	}

	if out := e.stdout.(*bytes.Buffer).String(); out != "" { //nolint:forcetypeassert
		t.Errorf("stdout = %q, want nothing", out)
	}
}

func TestNativeTypesCheckFailsOnAStaleFileAndLeavesItAlone(t *testing.T) {
	t.Parallel()

	e, path := nativeTypesEnv(t)

	if code := run(context.Background(), e, []string{"codebase", "native-types"}); code != 0 {
		t.Fatalf("native-types: exit %d: %s", code, e.stderr)
	}

	stale := "// edited by hand\n"
	if err := os.WriteFile(path, []byte(stale), 0o600); err != nil {
		t.Fatal(err)
	}

	if code := run(context.Background(), e, []string{"codebase", "native-types", "--check"}); code == 0 {
		t.Fatal("--check passed on a file that differs from the generated one")
	}

	if got := e.stderr.(*bytes.Buffer).String(); !strings.Contains(got, "out of date: "+path) { //nolint:forcetypeassert
		t.Errorf("stderr = %q, want it to name the stale file", got)
	}

	if content, _ := os.ReadFile(path); string(content) != stale { //nolint:gosec // G304: a file of the test's temporary workspace
		t.Error("--check changed the file")
	}

	// Running it without --check brings the file back.
	if code := run(context.Background(), e, []string{"codebase", "native-types"}); code != 0 {
		t.Fatalf("native-types: exit %d: %s", code, e.stderr)
	}

	if content, _ := os.ReadFile(path); string(content) == stale { //nolint:gosec // G304: a file of the test's temporary workspace
		t.Error("native-types did not rewrite the stale file")
	}
}

func TestNativeTypesCheckFailsWhenTheFileIsMissing(t *testing.T) {
	t.Parallel()

	e, path := nativeTypesEnv(t)

	if code := run(context.Background(), e, []string{"codebase", "native-types", "--check"}); code == 0 {
		t.Fatal("--check passed without a generated file")
	}

	if _, err := os.Stat(path); err == nil {
		t.Error("--check wrote the missing file")
	}
}

func TestNativeTypesNeedsThePackageOfTheOwner(t *testing.T) {
	t.Parallel()

	e := testEnv(t)

	if code := run(context.Background(), e, []string{"codebase", "native-types"}); code == 0 {
		t.Fatal("native-types succeeded in a workspace without the owner package")
	}

	if got := e.stderr.(*bytes.Buffer).String(); !strings.Contains(got, "@eserstack/codebase") { //nolint:forcetypeassert
		t.Errorf("stderr = %q, want it to name the owner", got)
	}
}
