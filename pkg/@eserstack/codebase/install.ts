/**
 * Show the installation status of git hooks expected by the manifest.
 */
export const statusMain = async (
  cliArgs?: readonly string[],
): Promise<shellArgs.CliResult<void>> => {
  const parsed = parseHelpArgs(cliArgs);

  const out = streams.output({
    renderer,
    sink: streams.sinks.stdout(),
  });

  if (parsed.help) {
    out.writeln("eser codebase status — Show git hook installation status");
    await out.close();
    return primitives.results.ok(undefined);
  }

  const gitDir = await findGitDir();
  if (gitDir === null) {
    out.writeln(span.red("Error: not inside a git repository"));
    await out.close();
    return primitives.results.fail({ exitCode: 1 });
  }

  const hooksDir = standards.crossRuntime.runtime.path.join(gitDir, "hooks");

  // Load manifest
  const cwd = standards.crossRuntime.runtime.process.cwd();
  const raw = await configManifest.loadManifest(cwd);
  if (raw === null) {
    out.writeln(
      span.red("Error: no .eser/manifest.yml found in current directory"),
    );
    await out.close();
    return primitives.results.fail({ exitCode: 1 });
  }

  const events = extractEvents(raw);
  if (events.length === 0) {
    out.writeln(span.dim("No workflow events found in manifest."));
    await out.close();
    return primitives.results.ok(undefined);
  }

  // The hook files are only read, so they are read concurrently; the report
  // below keeps the manifest order.
  const statuses = await Promise.all(
    events.map(async (event): Promise<span.Span | null> => {
      const mapping = EVENT_TO_HOOK[event];
      if (mapping === undefined) {
        return null;
      }

      const hookPath = standards.crossRuntime.runtime.path.join(
        hooksDir,
        mapping.hookName,
      );
      try {
        const content =
          await standards.crossRuntime.runtime.fs.readTextFile(hookPath);
        return content.includes(MARKER)
          ? span.green("managed (@eser)")
          : span.yellow("user hook");
      } catch {
        return span.dim("not installed");
      }
    }),
  );

  out.writeln(span.bold("Git hook status:"));
  out.writeln();

  for (const [index, event] of events.entries()) {
    const mapping = EVENT_TO_HOOK[event];
    const statusSpan = statuses[index] ?? null;
    if (mapping === undefined || statusSpan === null) {
      out.writeln(
        span.text("  "),
        span.dim(event.padEnd(14)),
        span.text(" "),
        span.dim("(no hook mapping)"),
      );
      continue;
    }

    out.writeln(span.text(`  ${mapping.hookName.padEnd(14)} `), statusSpan);
  }

  out.writeln();
  await out.close();
  return primitives.results.ok(undefined);
};

