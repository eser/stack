/** The flags of `eser codebase install`. */
export type InstallArgs = {
  readonly help: boolean;
  readonly force: boolean;
  readonly dryRun: boolean;
};

/** Parse the install arguments: `--force` (`-f`), `--dry-run` (`-n`), `--help` (`-h`). */
export const parseInstallArgs = (cliArgs?: readonly string[]): InstallArgs => {
  const { values } = shellFlags.parseArgs(cliArgs ?? [], {
    options: {
      force: { type: "boolean", short: "f" },
      "dry-run": { type: "boolean", short: "n" },
      help: { type: "boolean", short: "h" },
    },
  });

  return {
    help: values["help"] === true,
    force: values["force"] === true,
    dryRun: values["dry-run"] === true,
  };
};

/** Parse the arguments of `uninstall` and `status`, which only know `--help` (`-h`). */
export const parseHelpArgs = (
  cliArgs?: readonly string[],
): { readonly help: boolean } => {
  const { values } = shellFlags.parseArgs(cliArgs ?? [], {
    options: { help: { type: "boolean", short: "h" } },
  });

  return { help: values["help"] === true };
};

/**
 * Install managed git hooks based on `.eser/manifest.yml` workflow events.
 *
 * Flags:
 *   --force     Overwrite non-managed hooks
 *   --dry-run   Show what would happen without writing
 *   --help      Show usage
 */
export const main = async (
  cliArgs?: readonly string[],
): Promise<shellArgs.CliResult<void>> => {
  const parsed = parseInstallArgs(cliArgs);

  const out = streams.output({
    renderer,
    sink: streams.sinks.stdout(),
  });

  if (parsed.help) {
    out.writeln(
      "eser codebase install — Install git hooks from .eser/manifest.yml",
    );
    out.writeln();
    out.writeln("Flags:");
    out.writeln("  --force, -f     Overwrite non-managed hooks");
    out.writeln("  --dry-run, -n   Show what would happen without writing");
    out.writeln("  --help, -h      Show this help");
    await out.close();
    return primitives.results.ok(undefined);
  }

  const { force, dryRun } = parsed;

  // 1. Find .git directory
  const gitDir = await findGitDir();
  if (gitDir === null) {
    out.writeln(span.red("Error: not inside a git repository"));
    await out.close();
    return primitives.results.fail({ exitCode: 1 });
  }

  const hooksDir = standards.crossRuntime.runtime.path.join(gitDir, "hooks");

  // 2. Load manifest
  const cwd = standards.crossRuntime.runtime.process.cwd();
  const raw = await configManifest.loadManifest(cwd);
  if (raw === null) {
    out.writeln(
      span.red("Error: no .eser/manifest.yml found in current directory"),
    );
    await out.close();
    return primitives.results.fail({ exitCode: 1 });
  }

  // 3. Extract events
  const events = extractEvents(raw);
  if (events.length === 0) {
    out.writeln(span.yellow("No workflow events found — nothing to install."));
    await out.close();
    return primitives.results.ok(undefined);
  }

  // 4. Ensure hooks directory exists
  if (!dryRun) {
    await standards.crossRuntime.runtime.fs.ensureDir(hooksDir);
  }

  // 5. Install hooks
  const cliCmd = await resolveCliCommand();
  let installed = 0;
  let skipped = 0;
  let updated = 0;

  for (const event of events) {
    const mapping = EVENT_TO_HOOK[event];
    if (mapping === undefined) {
      out.writeln(
        span.dim(`  skip  ${event} (unknown event, no hook mapping)`),
      );
      continue;
    }

    const { hookName, args } = mapping;
    const hookPath = standards.crossRuntime.runtime.path.join(
      hooksDir,
      hookName,
    );
    const script = generateHookScript(cliCmd, event, args);

    let exists = false;
    let isManaged = false;

    try {
      // Hooks are written one at a time, so a failed write stops before the
      // next hook changes and the report follows the manifest order.
      const existing =
        // oxlint-disable-next-line no-await-in-loop
        await standards.crossRuntime.runtime.fs.readTextFile(hookPath);
      exists = true;
      isManaged = existing.includes(MARKER);
    } catch {
      // file does not exist
    }

    if (dryRun) {
      if (!exists) {
        out.writeln(span.blue(`  would create  ${hookName}`));
      } else if (isManaged) {
        out.writeln(span.blue(`  would update  ${hookName} (managed)`));
      } else if (force) {
        out.writeln(span.yellow(`  would overwrite  ${hookName} (--force)`));
      } else {
        out.writeln(
          span.yellow(
            `  would skip  ${hookName} (user hook; use --force to overwrite)`,
          ),
        );
      }
      continue;
    }

    if (exists && !isManaged && !force) {
      out.writeln(
        span.yellow(
          `  skip  ${hookName} — user hook exists (use --force to overwrite)`,
        ),
      );
      skipped++;
      continue;
    }

    // One hook at a time, as above.
    // oxlint-disable-next-line no-await-in-loop
    await standards.crossRuntime.runtime.fs.writeTextFile(hookPath, script);

    // chmod +x (non-fatal on platforms without chmod support)
    try {
      // One hook at a time, as above.
      // oxlint-disable-next-line no-await-in-loop
      await standards.crossRuntime.runtime.fs.chmod(hookPath, 0o755);
    } catch {
      // Windows doesn't support chmod — hook will still work via shebang
    }

    if (exists && isManaged) {
      out.writeln(span.green(`  updated  ${hookName}`));
      updated++;
    } else {
      out.writeln(span.green(`  installed  ${hookName}`));
      installed++;
    }
  }

  // Summary
  out.writeln();
  const parts: string[] = [];
  if (installed > 0) parts.push(`${installed} installed`);
  if (updated > 0) parts.push(`${updated} updated`);
  if (skipped > 0) parts.push(`${skipped} skipped`);
  if (dryRun) {
    out.writeln(span.dim("(dry run — no changes made)"));
  } else if (parts.length > 0) {
    out.writeln(span.green(`Done: ${parts.join(", ")}.`));
  } else {
    out.writeln(span.dim("Nothing to do."));
  }

  await out.close();
  return primitives.results.ok(undefined);
};

