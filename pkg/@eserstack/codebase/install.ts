/**
 * Git hook installation — installs, uninstalls, and reports status of
 * managed git hooks derived from `.eser/manifest.yml` workflow events.
 *
 * @module
 */

import * as shellFlags from "@eserstack/shell/args/flags";
import * as span from "@eserstack/streams/span";
import * as streams from "@eserstack/streams";
import * as primitives from "@eserstack/primitives";
import * as standards from "@eserstack/standards";
import * as configManifest from "@eserstack/config/manifest";
import type * as shellArgs from "@eserstack/shell/args";
import * as cliSupport from "./cli-support.ts";

// =============================================================================
// Constants
// =============================================================================

/** Maps manifest event names to git hook filenames and extra shell args. */
const EVENT_TO_HOOK: Record<string, { hookName: string; args: string }> = {
  precommit: { hookName: "pre-commit", args: "" },
  commitmsg: { hookName: "commit-msg", args: '-- "$1"' },
  prepush: { hookName: "pre-push", args: "" },
};

/** Marker comment placed in managed hook scripts. */
const MARKER = "# @eser managed hook";

// =============================================================================
// Helpers
// =============================================================================

/**
 * Resolve the command a hook runs to reach the CLI.
 *
 * Uses `detectExecutionContext()` to determine how the CLI was invoked,
 * honoring the user's chosen invocation method for the hook command.
 */
const resolveCliCommand = async (): Promise<string> => {
  const ctx = await standards.crossRuntime.detectExecutionContext({
    command: "eser",
    devCommand: "pnpm cli",
    npmPackage: "eser",
  });

  return ctx.command;
};

/**
 * Generate the shell script content for a git hook.
 */
const generateHookScript = (
  cliCmd: string,
  event: string,
  args: string,
): string => {
  const argsStr = args.length > 0 ? ` ${args}` : "";
  const command = `${cliCmd} workflows run -e ${event}${argsStr}`;

  return [
    "#!/bin/sh",
    `${MARKER} — generated by \`eser codebase install\``,
    "# Do not edit. Re-run `eser codebase install` to update.",
    "",
    command,
    "",
  ].join("\n");
};

/**
 * Locate the `.git` directory for the current repository.
 */
const findGitDir = async (): Promise<string | null> => {
  try {
    const output = await standards.crossRuntime.runtime.exec.exec("git", [
      "rev-parse",
      "--git-dir",
    ]);
    const dir = output.trim();
    if (dir.length > 0) return dir;
  } catch {
    // fall through
  }

  // Fallback: check cwd
  const cwd = standards.crossRuntime.runtime.process.cwd();
  const dotGit = standards.crossRuntime.runtime.path.join(cwd, ".git");
  try {
    const info = await standards.crossRuntime.runtime.fs.stat(dotGit);
    if (info.isDirectory) return dotGit;
  } catch {
    // not found
  }

  return null;
};

/**
 * Extract unique events from a manifest's workflows array.
 */
const extractEvents = (raw: Record<string, unknown>): string[] => {
  const workflows = raw["workflows"] as
    | readonly { on?: readonly string[] }[]
    | undefined;
  if (!Array.isArray(workflows)) return [];

  const events = new Set<string>();
  for (const wf of workflows) {
    if (Array.isArray(wf.on)) {
      for (const ev of wf.on) {
        if (typeof ev === "string") events.add(ev);
      }
    }
  }
  return [...events];
};

