package collectorfx

import (
	"slices"
	"strconv"
	"strings"
)

const (
	manifestHeader = "// This file is generated by @eserstack/collector. Your changes might be overwritten.\n\n"
	importPrefix   = "$$"
	// The references are placed in the manifest as JSON strings wrapped in
	// these markers, and the markers and quotes are cut out afterwards.
	placeholderPrefix = "##!!//__"
	placeholderSuffix = "__//!!##"
)

// GenerateManifestSource writes the source of a manifest module: one
// namespace import per entry and an exported manifest object that lists
// every entry's references, as @eserstack/collector wrote it in TypeScript.
//
//	// This file is generated by @eserstack/collector. Your changes might be overwritten.
//
//	import * as $$routes_index from "./routes/index.ts";
//
//	export const manifest = {
//	  "exports": [
//	    $$routes_index.handler
//	  ]
//	};
//
// The import path is the entry's RelPath normalized as Node's
// path.posix.normalize does, with "\" turned into "/" and "./" put in front
// unless it starts with ".". The namespace name is "$$" and the
// SpecifierToIdentifier answer for RelPath. The imports and the references
// are each sorted by compareNatural, and a reference is written the way
// JSON.stringify writes a string, without the quotes.
//
// The source is not formatted; run it through a formatter such as oxfmt for
// canonical style.
func GenerateManifestSource(entries []ManifestEntry) string {
	used := make(map[string]struct{}, len(entries))
	imports := make([]string, 0, len(entries))
	references := make([]string, 0, len(entries))

	for _, entry := range entries {
		identifier := importPrefix + SpecifierToIdentifier(entry.RelPath, used)

		imports = append(imports, "import * as "+identifier+` from "`+toImportSpecifier(entry.RelPath)+`";`)

		for _, name := range entry.Exports {
			references = append(references, placeholderPrefix+identifier+"."+name+placeholderSuffix)
		}
	}

	slices.SortStableFunc(imports, compareNatural)
	slices.SortStableFunc(references, compareNatural)

	var b strings.Builder

	b.WriteString(manifestHeader)
	b.WriteString(strings.Join(imports, "\n"))
	b.WriteString("\n\nexport const manifest = ")
	b.WriteString(serializeManifest(references))
	b.WriteString(";\n")

	return b.String()
}

// serializeManifest writes { exports: references } as
// JSON.stringify(value, null, 2) does and then cuts the placeholder markers
// and their quotes out, so each reference becomes code.
func serializeManifest(references []string) string {
	var b strings.Builder

	b.WriteString("{\n  \"exports\": [")

	if len(references) > 0 {
		for i, reference := range references {
			if i > 0 {
				b.WriteString(",")
			}

			b.WriteString("\n    ")
			writeJSONString(&b, reference)
		}

		b.WriteString("\n  ")
	}

	b.WriteString("]\n}")

	out := strings.ReplaceAll(b.String(), `"`+placeholderPrefix, "")

	return strings.ReplaceAll(out, placeholderSuffix+`"`, "")
}

// writeJSONString writes s quoted the way JavaScript's JSON.stringify quotes
// a string: '"' and '\' escaped, \b \t \n \f \r for those controls, \u00XX
// for the other ones below U+0020, and everything else as it is.
func writeJSONString(b *strings.Builder, s string) {
	b.WriteByte('"')

	for _, r := range s {
		switch r {
		case '"':
			b.WriteString(`\"`)
		case '\\':
			b.WriteString(`\\`)
		case '\b':
			b.WriteString(`\b`)
		case '\t':
			b.WriteString(`\t`)
		case '\n':
			b.WriteString(`\n`)
		case '\f':
			b.WriteString(`\f`)
		case '\r':
			b.WriteString(`\r`)
		default:
			if r < 0x20 {
				b.WriteString(`\u00`)
				b.WriteString(strconv.FormatInt(int64(r)>>4, 16))
				b.WriteString(strconv.FormatInt(int64(r)&0xf, 16))

				continue
			}

			b.WriteRune(r)
		}
	}

	b.WriteByte('"')
}

// toImportSpecifier turns a project-relative path into an import specifier:
// normalized, with forward slashes, and starting with ".".
func toImportSpecifier(file string) string {
	specifier := strings.ReplaceAll(posixNormalize(file), `\`, "/")

	if !strings.HasPrefix(specifier, ".") {
		return "./" + specifier
	}

	return specifier
}

// posixNormalize normalizes path as Node's path.posix.normalize does: "."
// segments and repeated "/" drop out, ".." removes the segment before it
// (and stays when there is none, unless the path is absolute), a trailing "/"
// stays, and an empty result is "." (or "./" for a trailing "/").
func posixNormalize(path string) string {
	if path == "" {
		return "."
	}

	isAbsolute := path[0] == '/'
	trailingSeparator := path[len(path)-1] == '/'

	normalized := normalizePosixSegments(path, !isAbsolute)

	if normalized == "" {
		switch {
		case isAbsolute:
			return "/"
		case trailingSeparator:
			return "./"
		default:
			return "."
		}
	}

	if trailingSeparator {
		normalized += "/"
	}

	if isAbsolute {
		return "/" + normalized
	}

	return normalized
}

// normalizePosixSegments is Node's normalizeString for the "/" separator.
// Node counts lengths in UTF-16 units and this in bytes; the two only meet
// in tests that a ".." segment passes or fails the same way either way.
func normalizePosixSegments(path string, allowAboveRoot bool) string {
	res := ""
	lastSegmentLength := 0
	lastSlash := -1
	dots := 0

	var code byte

	for i := 0; i <= len(path); i++ {
		switch {
		case i < len(path):
			code = path[i]
		case code == '/':
			return res
		default:
			code = '/'
		}

		switch {
		case code == '/':
			switch {
			case lastSlash == i-1 || dots == 1:
				// An empty or "." segment: nothing to add.
			case dots == 2:
				if len(res) < 2 || lastSegmentLength != 2 ||
					res[len(res)-1] != '.' || res[len(res)-2] != '.' {
					if len(res) > 2 {
						lastSlashIndex := strings.LastIndexByte(res, '/')
						if lastSlashIndex == -1 {
							res = ""
							lastSegmentLength = 0
						} else {
							res = res[:lastSlashIndex]
							lastSegmentLength = len(res) - 1 - strings.LastIndexByte(res, '/')
						}

						lastSlash = i
						dots = 0

						continue
					} else if len(res) != 0 {
						res = ""
						lastSegmentLength = 0
						lastSlash = i
						dots = 0

						continue
					}
				}

				if allowAboveRoot {
					if len(res) > 0 {
						res += "/.."
					} else {
						res = ".."
					}

					lastSegmentLength = 2
				}
			default:
				segment := path[lastSlash+1 : i]

				if len(res) > 0 {
					res += "/" + segment
				} else {
					res = segment
				}

				lastSegmentLength = i - lastSlash - 1
			}

			lastSlash = i
			dots = 0
		case code == '.' && dots != -1:
			dots++
		default:
			dots = -1
		}
	}

	return res
}
