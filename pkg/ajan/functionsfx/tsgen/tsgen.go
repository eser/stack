// Package tsgen writes the TypeScript types of native functions from their
// descriptors (ADR 0011). The Go function is the source: its input and output
// JSON Schemas, derived from its Go types or written beside them, become the
// types a TypeScript caller passes to fromNative.
//
// The output is the text of one TypeScript module for the functions one
// package owns. It is deterministic, so a check can compare it with the file on
// disk.
package tsgen

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"regexp"
	"slices"
	"strings"

	"github.com/eser/stack/pkg/ajan/functionsfx"
)

// Errors of Source.
var (
	// ErrNameClash is returned when two functions would get the same type name.
	ErrNameClash = errors.New("two functions give the same type name")
	// ErrBadSchema is returned for a schema that is not JSON or not an object.
	ErrBadSchema = errors.New("schema cannot be read")
	// ErrNoOwner is returned for a function that names no owner package, so
	// there is no package to write its types into.
	ErrNoOwner = errors.New("function has no owner package")
)

// ModuleFile is the name of the generated module in the package that owns the
// functions.
const ModuleFile = "native-functions.ts"

const header = `// Copyright 2023-present Eser Ozvataf and other contributors. All rights reserved. Apache-2.0 license.

// Generated by ` + "`go run ./cmd/eser codebase native-types`" + ` from the descriptors of the
// native functions this package owns (pkg/ajan/functionsfx). Do not edit it by
// hand: change the Go function and run the command again.

/**
 * The input and output types of the native functions this package owns, for
 * ` + "`fromNative`" + ` of ` + "`@eserstack/functions/native`" + `.
 *
 * @module
 */
`

// Files renders the module of every owner package: the key is the owner, such
// as "@eserstack/codebase", and the value the text of its ModuleFile. A function
// without an owner is ErrNoOwner.
func Files(descriptors []functionsfx.Descriptor) (map[string][]byte, error) {
	byOwner := map[string][]functionsfx.Descriptor{}

	for i := range descriptors {
		if descriptors[i].Owner == "" {
			return nil, fmt.Errorf("%w: %q; name one with functionsfx.WithOwner", ErrNoOwner, descriptors[i].Name)
		}

		byOwner[descriptors[i].Owner] = append(byOwner[descriptors[i].Owner], descriptors[i])
	}

	files := make(map[string][]byte, len(byOwner))

	for owner, owned := range byOwner {
		source, err := Source(owned)
		if err != nil {
			return nil, fmt.Errorf("types of %s: %w", owner, err)
		}

		files[owner] = source
	}

	return files, nil
}

// Source renders the TypeScript module of the descriptors, which must all be
// owned by one package. A function that has no schema gets the type unknown.
func Source(descriptors []functionsfx.Descriptor) ([]byte, error) {
	sorted := slices.Clone(descriptors)
	slices.SortFunc(sorted, func(a, b functionsfx.Descriptor) int { return strings.Compare(a.Name, b.Name) })

	var out bytes.Buffer

	out.WriteString(header)

	names := map[string]string{}
	outputs := map[string]string{}

	for i := range sorted {
		descriptor := &sorted[i]
		base := pascal(descriptor.Name)

		if owner, taken := names[base]; taken {
			return nil, fmt.Errorf("%w: %q and %q are both %s", ErrNameClash, owner, descriptor.Name, base)
		}

		names[base] = descriptor.Name

		input, err := typeOfSchema(descriptor.InputSchema, true)
		if err != nil {
			return nil, fmt.Errorf("function %q input: %w", descriptor.Name, err)
		}

		output, err := typeOfSchema(descriptor.OutputSchema, false)
		if err != nil {
			return nil, fmt.Errorf("function %q output: %w", descriptor.Name, err)
		}

		fmt.Fprintf(&out, "\n%s\nexport type %sInput = %s;\n", doc(
			"Input of the native function `"+descriptor.Name+"`.", descriptor.Description), base, input)

		// Functions with the same output share one type: the first defines it
		// and the others alias it.
		if first, shared := outputs[output]; shared {
			fmt.Fprintf(&out, "\n%s\nexport type %sOutput = %s;\n", doc(
				"Output of the native function `"+descriptor.Name+"`.", ""), base, first)
		} else {
			outputs[output] = base + "Output"

			fmt.Fprintf(&out, "\n%s\nexport type %sOutput = %s;\n", doc(
				"Output of the native function `"+descriptor.Name+"`.", ""), base, output)
		}
	}

	out.WriteString("\n/** The native functions of this package, by name. */\nexport type NativeFunctions = {\n")

	for i := range sorted {
		base := pascal(sorted[i].Name)

		// A function that streams answers its output once for each item.
		streams := ""
		if sorted[i].Stream {
			streams = "    readonly stream: true;\n"
		}

		fmt.Fprintf(&out, "  readonly %s: {\n    readonly input: %sInput;\n    readonly output: %sOutput;\n%s  };\n",
			key(sorted[i].Name), base, base, streams)
	}

	out.WriteString("};\n")

	return out.Bytes(), nil
}

// doc renders a one-line or two-line JSDoc comment.
func doc(summary, description string) string {
	if description == "" {
		return "/** " + summary + " */"
	}

	return "/**\n * " + summary + "\n *\n * " + description + "\n */"
}

var identifierPattern = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

// key renders an object key, quoted only when it is not an identifier.
func key(name string) string {
	if identifierPattern.MatchString(name) {
		return name
	}

	encoded, _ := json.Marshal(name) //nolint:errchkjson // a string always encodes

	return string(encoded)
}

// pascal turns a function name such as "validate-no-todos" into ValidateNoTodos.
func pascal(name string) string {
	var out strings.Builder

	for part := range strings.FieldsFuncSeq(name, func(r rune) bool { return r == '-' || r == '.' || r == '_' }) {
		out.WriteString(strings.ToUpper(part[:1]))
		out.WriteString(part[1:])
	}

	return out.String()
}

// typeOfSchema renders the type of a JSON Schema document. An input type of an
// object that lists properties also takes others, as the schema accepts them
// and the engine adds some; an output type is closed.
func typeOfSchema(raw json.RawMessage, input bool) (string, error) {
	if len(bytes.TrimSpace(raw)) == 0 {
		return "unknown", nil
	}

	var node any
	if err := json.Unmarshal(raw, &node); err != nil {
		return "", fmt.Errorf("%w: %w", ErrBadSchema, err)
	}

	return typeOf(node, 0, input)
}

func typeOf(node any, depth int, input bool) (string, error) {
	fields, isObject := node.(map[string]any)
	if !isObject {
		return "unknown", nil
	}

	if values, ok := fields["enum"].([]any); ok {
		return literals(values)
	}

	for _, keyword := range []string{"oneOf", "anyOf"} {
		if branches, ok := fields[keyword].([]any); ok {
			return union(branches, depth, input)
		}
	}

	switch kind := fields["type"].(type) {
	case string:
		return typeOfKind(kind, fields, depth, input)
	case []any:
		parts := make([]string, 0, len(kind))

		for _, item := range kind {
			name, _ := item.(string)

			part, err := typeOfKind(name, fields, depth, input)
			if err != nil {
				return "", err
			}

			parts = append(parts, part)
		}

		return strings.Join(unique(parts), " | "), nil
	default:
		return "unknown", nil
	}
}

func typeOfKind(kind string, fields map[string]any, depth int, input bool) (string, error) {
	switch kind {
	case "string":
		return "string", nil
	case "integer", "number":
		return "number", nil
	case "boolean":
		return "boolean", nil
	case "null":
		return "null", nil
	case "array":
		element, err := typeOf(fields["items"], depth, input)
		if err != nil {
			return "", err
		}

		if strings.ContainsAny(element, "{|<") {
			return "ReadonlyArray<" + element + ">", nil
		}

		return "readonly " + element + "[]", nil
	case "object":
		return typeOfObject(fields, depth, input)
	default:
		return "unknown", nil
	}
}

func typeOfObject(fields map[string]any, depth int, input bool) (string, error) {
	properties, _ := fields["properties"].(map[string]any)

	if len(properties) == 0 {
		values := "unknown"

		if extra, isSchema := fields["additionalProperties"].(map[string]any); isSchema {
			rendered, err := typeOf(extra, depth, input)
			if err != nil {
				return "", err
			}

			values = rendered
		}

		return "Readonly<Record<string, " + values + ">>", nil
	}

	required := map[string]bool{}

	if list, ok := fields["required"].([]any); ok {
		for _, name := range list {
			if text, isText := name.(string); isText {
				required[text] = true
			}
		}
	}

	names := make([]string, 0, len(properties))
	for name := range properties {
		names = append(names, name)
	}

	slices.Sort(names)

	indent := strings.Repeat("  ", depth+1)

	var out strings.Builder

	out.WriteString("{\n")

	for _, name := range names {
		property, _ := properties[name].(map[string]any)

		rendered, err := typeOf(property, depth+1, input)
		if err != nil {
			return "", fmt.Errorf("property %q: %w", name, err)
		}

		if description, ok := property["description"].(string); ok && description != "" {
			fmt.Fprintf(&out, "%s/** %s */\n", indent, description)
		}

		optional := ""
		if !required[name] {
			optional = "?"
		}

		separator := ": "
		if strings.HasPrefix(rendered, "\n") {
			separator = ":"
		}

		fmt.Fprintf(&out, "%sreadonly %s%s%s%s;\n", indent, key(name), optional, separator, rendered)
	}

	// A schema without additionalProperties: false accepts other properties, and
	// an input takes them: the workflow engine adds root, fix and more.
	if allowed, isBool := fields["additionalProperties"].(bool); input && (!isBool || allowed) {
		fmt.Fprintf(&out, "%sreadonly [key: string]: unknown;\n", indent)
	}

	out.WriteString(strings.Repeat("  ", depth))
	out.WriteString("}")

	return out.String(), nil
}

func literals(values []any) (string, error) {
	parts := make([]string, 0, len(values))

	for _, value := range values {
		encoded, err := json.Marshal(value)
		if err != nil {
			return "", fmt.Errorf("%w: enum value %v: %w", ErrBadSchema, value, err)
		}

		parts = append(parts, string(encoded))
	}

	return strings.Join(unique(parts), " | "), nil
}

func union(branches []any, depth int, input bool) (string, error) {
	parts := make([]string, 0, len(branches))

	for _, branch := range branches {
		part, err := typeOf(branch, depth, input)
		if err != nil {
			return "", err
		}

		parts = append(parts, part)
	}

	return joinUnion(unique(parts), depth), nil
}

// joinUnion joins the members of a union. When a member spans lines it breaks
// the union after the colon and leads each member with a bar, indented one level
// in from its property, the layout the repository's formatter gives it.
func joinUnion(parts []string, depth int) string {
	multiline := slices.ContainsFunc(parts, func(part string) bool { return strings.Contains(part, "\n") })
	if !multiline {
		return strings.Join(parts, " | ")
	}

	lead := "\n" + strings.Repeat("  ", depth+1) + "| "

	var out strings.Builder

	for _, part := range parts {
		out.WriteString(lead)
		out.WriteString(strings.ReplaceAll(part, "\n", "\n    "))
	}

	return out.String()
}

func unique(parts []string) []string {
	seen := map[string]bool{}
	kept := make([]string, 0, len(parts))

	for _, part := range parts {
		if !seen[part] {
			seen[part] = true
			kept = append(kept, part)
		}
	}

	return kept
}
