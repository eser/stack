func TestSchemasOfEveryKeywordTheValidatorsUse(t *testing.T) {
	t.Parallel()

	descriptor := descriptorOf(t, "keywords", functionsfx.WithInputSchema(json.RawMessage(`{
		"type": "object",
		"properties": {
			"convention": {"enum": ["kebab-case", "snake_case"]},
			"either": {"oneOf": [{"type": "array", "items": {"type": "string"}}, {"type": "string"}]},
			"maybe": {"type": ["string", "null"]},
			"max": {"type": "integer", "minimum": 0},
			"free": {"type": "object"},
			"quoted-key": {"type": "boolean"},
			"anything": {}
		},
		"required": ["convention"]
	}`)))

	source, err := tsgen.Source([]functionsfx.Descriptor{descriptor})
	if err != nil {
		t.Fatalf("Source: %v", err)
	}

	for _, want := range []string{
		`readonly convention: "kebab-case" | "snake_case";`,
		"readonly either?: readonly string[] | string;",
		"readonly maybe?: string | null;",
		"readonly max?: number;",
		"readonly free?: Readonly<Record<string, unknown>>;",
		`readonly "quoted-key"?: boolean;`,
		"readonly anything?: unknown;",
	} {
		if !strings.Contains(string(source), want) {
			t.Errorf("the module lacks %q:\n%s", want, source)
		}
	}
}

