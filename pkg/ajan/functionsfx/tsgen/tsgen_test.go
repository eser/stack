func TestFilesGroupsByOwnerAndNeedsOne(t *testing.T) {
	t.Parallel()

	other, err := functionsfx.NewFunction("other",
		functionsfx.Handler[string, string](func(_ context.Context, input string) (string, error) { return input, nil }),
		functionsfx.WithOwner("@eserstack/other"),
	)
	if err != nil {
		t.Fatalf("NewFunction: %v", err)
	}

	files, err := tsgen.Files([]functionsfx.Descriptor{descriptorOf(t, "greet"), other.Descriptor()})
	if err != nil {
		t.Fatalf("Files: %v", err)
	}

	if len(files) != 2 || files["@eserstack/greeter"] == nil || files["@eserstack/other"] == nil {
		t.Errorf("files = %v, want one module for each owner", len(files))
	}

	if strings.Contains(string(files["@eserstack/greeter"]), "OtherInput") {
		t.Error("a function appears in the module of another owner")
	}

	orphan, err := functionsfx.NewFunction("orphan",
		functionsfx.Handler[string, string](func(_ context.Context, input string) (string, error) { return input, nil }),
	)
	if err != nil {
		t.Fatalf("NewFunction: %v", err)
	}

	if _, err := tsgen.Files([]functionsfx.Descriptor{orphan.Descriptor()}); !errors.Is(err, tsgen.ErrNoOwner) {
		t.Errorf("a function without an owner: error = %v, want ErrNoOwner", err)
	}
}

func TestAFunctionThatStreamsIsMarkedAndItsOutputIsOneItem(t *testing.T) {
	t.Parallel()

	function, err := functionsfx.NewStreamFunction("count-up",
		functionsfx.StreamHandler[greetInput, greetOutput](func(context.Context, greetInput) iter.Seq2[greetOutput, error] {
			return func(func(greetOutput, error) bool) {}
		}),
		functionsfx.WithOwner("@eserstack/greeter"),
		functionsfx.WithSchemasOf[greetInput, greetOutput](),
	)
	if err != nil {
		t.Fatalf("NewStreamFunction: %v", err)
	}

	plain := descriptorOf(t, "plain", functionsfx.WithSchemasOf[greetInput, greetOutput]())

	source, err := tsgen.Source([]functionsfx.Descriptor{function.Descriptor(), plain})
	if err != nil {
		t.Fatalf("Source: %v", err)
	}

	text := string(source)

	if !strings.Contains(text, "readonly count-up: {") && !strings.Contains(text, `readonly "count-up": {`) {
		t.Fatalf("the module lacks the entry of the stream function:\n%s", text)
	}

	if !strings.Contains(text, "    readonly output: CountUpOutput;\n    readonly stream: true;\n  };") {
		t.Errorf("the stream function is not marked:\n%s", text)
	}

	if strings.Count(text, "readonly stream: true;") != 1 {
		t.Errorf("a function that does not stream is marked as one:\n%s", text)
	}
}
