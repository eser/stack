type greetInput struct {
	Name   string   `json:"name" description:"Who to greet"`
	Shout  bool     `json:"shout,omitempty"`
	Tags   []string `json:"tags,omitempty"`
	Retry  *int     `json:"retry"`
	Config struct {
		Level string `json:"level"`
	} `json:"config"`
}

type greetOutput struct {
	Text string         `json:"text"`
	Meta map[string]int `json:"meta,omitempty"`
}

func descriptorOf(t *testing.T, name string, options ...functionsfx.Option) functionsfx.Descriptor {
	t.Helper()

	options = append(options, functionsfx.WithOwner("@eserstack/greeter"))

	function, err := functionsfx.NewFunction(name,
		functionsfx.Handler[greetInput, greetOutput](func(context.Context, greetInput) (greetOutput, error) {
			return greetOutput{}, nil
		}),
		options...,
	)
	if err != nil {
		t.Fatalf("NewFunction(%q): %v", name, err)
	}

	return function.Descriptor()
}

func TestSourceWritesTheTypesOfAStructFunction(t *testing.T) {
	t.Parallel()

	source, err := tsgen.Source([]functionsfx.Descriptor{
		descriptorOf(t, "greet", functionsfx.WithSchemasOf[greetInput, greetOutput](), functionsfx.WithDescription("Greets by name")),
	})
	if err != nil {
		t.Fatalf("Source: %v", err)
	}

	text := string(source)

	for _, want := range []string{
		"// Generated by `go run ./cmd/eser codebase native-types`",
		"export type GreetInput = {",
		"  /** Who to greet */\n  readonly name: string;",
		"  readonly shout?: boolean;",
		"  readonly tags?: readonly string[];",
		"  readonly retry: number | null;",
		"  readonly config: {\n    readonly level: string;\n    readonly [key: string]: unknown;\n  };",
		"  readonly [key: string]: unknown;",
		"export type GreetOutput = {\n  readonly meta?: Readonly<Record<string, number>>;\n  readonly text: string;\n};",
		"Greets by name",
		"export type NativeFunctions = {\n  readonly greet: {\n    readonly input: GreetInput;\n    readonly output: GreetOutput;\n  };\n};",
	} {
		if !strings.Contains(text, want) {
			t.Errorf("the module lacks %q:\n%s", want, text)
		}
	}

	// An input is open at every level; an output is closed: it has no index signature.
	if strings.Count(text, "readonly [key: string]: unknown;") != 2 {
		t.Errorf("want an index signature on the input and on its nested config only:\n%s", text)
	}
}

func TestSourceIsDeterministic(t *testing.T) {
	t.Parallel()

	descriptors := []functionsfx.Descriptor{
		descriptorOf(t, "zeta", functionsfx.WithSchemasOf[greetInput, greetOutput]()),
		descriptorOf(t, "alpha", functionsfx.WithSchemasOf[greetInput, greetOutput]()),
	}
	reversed := []functionsfx.Descriptor{descriptors[1], descriptors[0]}

	first, err := tsgen.Source(descriptors)
	if err != nil {
		t.Fatalf("Source: %v", err)
	}

	second, err := tsgen.Source(reversed)
	if err != nil {
		t.Fatalf("Source: %v", err)
	}

	if string(first) != string(second) {
		t.Error("the module depends on the order of the descriptors")
	}

	if strings.Index(string(first), "AlphaInput") > strings.Index(string(first), "ZetaInput") {
		t.Error("functions are not sorted by name")
	}
}

func TestFunctionsWithTheSameOutputShareOneType(t *testing.T) {
	t.Parallel()

	source, err := tsgen.Source([]functionsfx.Descriptor{
		descriptorOf(t, "first", functionsfx.WithSchemasOf[greetInput, greetOutput]()),
		descriptorOf(t, "second", functionsfx.WithSchemasOf[greetInput, greetOutput]()),
	})
	if err != nil {
		t.Fatalf("Source: %v", err)
	}

	if text := string(source); !strings.Contains(text, "export type SecondOutput = FirstOutput;") {
		t.Errorf("the second output is not an alias of the first:\n%s", text)
	}
}

