// gen_unicode_tables writes unicode_tables.go, the cell width and grapheme
// cluster properties vt uses, and unicode_grapheme_cases_test.go, the UAX #29
// conformance cases of GraphemeBreakTest.txt, from the Unicode Character
// Database files listed in ucdFiles.
//
// The data files stay out of the repository. Each one is read from the
// directory -ucd, downloaded there first when it is missing, and checked
// against the SHA-256 recorded below, so the tables always come from the same
// bytes. Run it with go generate in this directory, or:
//
//	go run gen_unicode_tables.go -ucd ../../../../etc/temp/muxfx-vt/ucd-15.1.0
package main

import (
	"bufio"
	"bytes"
	"context"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log/slog"
	"net/http"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"time"
)

// unicodeVersion is the Unicode version the tables are generated from.
const unicodeVersion = "15.1.0"

const (
	downloadTimeout = 2 * time.Minute
	// maxFileSize bounds a download; the largest file is about 3 MB.
	maxFileSize = 16 << 20
)

type ucdFile struct {
	name   string
	url    string
	sha256 string
}

// ucdFiles are the inputs, with the SHA-256 of each as the Unicode
// Consortium published it for 15.1.0.
func ucdFiles() []ucdFile {
	const base = "https://www.unicode.org/Public/" + unicodeVersion + "/ucd/"

	return []ucdFile{
		{"EastAsianWidth.txt", base + "EastAsianWidth.txt", "b08191401dc125f4e84ef262a95754faae6b737c79538e17ea9664a63434e94e"},
		{"DerivedGeneralCategory.txt", base + "extracted/DerivedGeneralCategory.txt", "760720ac034f96b630a3055879a744e0907184e8aa811e89ba34583a7a487e85"},
		{"DerivedCoreProperties.txt", base + "DerivedCoreProperties.txt", "f55d0db69123431a7317868725b1fcbf1eab6b265d756d1bd7f0f6d9f9ee108b"},
		{"GraphemeBreakProperty.txt", base + "auxiliary/GraphemeBreakProperty.txt", "a7e52eee647e52dc210b8719b4d7037276f4b353810293d69377fc46374cec3f"},
		{"GraphemeBreakTest.txt", base + "auxiliary/GraphemeBreakTest.txt", "ed9c5e92fd0911ccbeeb63c97cb19c519ea272ff1112ce843abd991582dd848f"},
		{"emoji-data.txt", base + "emoji/emoji-data.txt", "d7aef489c8fe4c14f09ea5695200277c6b93ac82ac60845cdd2161b0d6835cc1"},
		{"emoji-variation-sequences.txt", base + "emoji/emoji-variation-sequences.txt", "8a67d0429a5831d91e744bc5170d43dc66ddccd42c6f532cbe421dc406b571fd"},
	}
}

const maxRune = 0x10FFFF

// The property bits, as unicode_tables.go reads them back (width.go).
const (
	propGCBShift   = 2
	propExtPict    = 1 << 6
	propVSBase     = 1 << 7
	propInCBShift  = 8
	propWidthWide  = 2
	propWidthOne   = 1
	propWidthZero  = 0
	gcbOther       = 0
	inCBNone       = 0
	softHyphen     = 0x00AD
	tablesFile     = "unicode_tables.go"
	casesFile      = "unicode_grapheme_cases_test.go"
	generatedBy    = "gen_unicode_tables.go"
	licenseHeader  = "// Copyright 2023-present Eser Ozvataf and other contributors. All rights reserved. Apache-2.0 license.\n\n"
	generatedLine  = "// Code generated by " + generatedBy + " from the Unicode " + unicodeVersion + " Character Database; DO NOT EDIT.\n\n"
	defaultUCDPath = "../../../../etc/temp/muxfx-vt/ucd-" + unicodeVersion
)

// The Grapheme_Cluster_Break values, in the order width.go numbers them.
var gcbNames = []string{
	"Other", "CR", "LF", "Control", "Extend", "ZWJ", "Regional_Indicator", "Prepend",
	"SpacingMark", "L", "V", "T", "LV", "LVT",
}

// The Indic_Conjunct_Break values, in the order width.go numbers them.
var inCBNames = []string{"None", "Linker", "Consonant", "Extend"}

func main() {
	ucdDir := flag.String("ucd", defaultUCDPath, "directory that holds (or receives) the UCD files")
	flag.Parse()

	if err := run(context.Background(), *ucdDir); err != nil {
		slog.Error("generate unicode tables", "error", err)
		os.Exit(1)
	}
}

func run(ctx context.Context, ucdDir string) error {
	data := map[string][]byte{}

	for _, f := range ucdFiles() {
		content, err := loadVerified(ctx, ucdDir, f)
		if err != nil {
			return err
		}

		data[f.name] = content
	}

	props, err := buildProperties(data)
	if err != nil {
		return err
	}

	if err := writeGo(tablesFile, tablesSource(props)); err != nil {
		return err
	}

	cases, err := parseBreakTest(data["GraphemeBreakTest.txt"])
	if err != nil {
		return err
	}

	return writeGo(casesFile, casesSource(cases))
}

// loadVerified reads a UCD file from dir, downloading it first when it is
// missing, and checks its SHA-256.
func loadVerified(ctx context.Context, dir string, f ucdFile) ([]byte, error) {
	path := filepath.Join(dir, f.name)

	content, err := os.ReadFile(path) //nolint:gosec // G304: the generator's own input directory
	if errors.Is(err, os.ErrNotExist) {
		content, err = download(ctx, f.url)
		if err != nil {
			return nil, err
		}

		if err := os.MkdirAll(dir, 0o750); err != nil {
			return nil, fmt.Errorf("create %s: %w", dir, err)
		}

		if err := os.WriteFile(path, content, 0o600); err != nil {
			return nil, fmt.Errorf("write %s: %w", path, err)
		}
	} else if err != nil {
		return nil, fmt.Errorf("read %s: %w", path, err)
	}

	sum := sha256.Sum256(content)
	if got := hex.EncodeToString(sum[:]); got != f.sha256 {
		return nil, fmt.Errorf("%s has SHA-256 %s, want %s; delete it to download it again", path, got, f.sha256)
	}

	return content, nil
}

func download(ctx context.Context, url string) ([]byte, error) {
	ctx, cancel := context.WithTimeout(ctx, downloadTimeout)
	defer cancel()

	req, err := http.NewRequestWithContext(ctx, http.MethodGet, url, nil)
	if err != nil {
		return nil, fmt.Errorf("request %s: %w", url, err)
	}

	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		return nil, fmt.Errorf("download %s: %w", url, err)
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("download %s: status %s", url, resp.Status)
	}

	content, err := io.ReadAll(io.LimitReader(resp.Body, maxFileSize+1))
	if err != nil {
		return nil, fmt.Errorf("download %s: %w", url, err)
	}

	if len(content) > maxFileSize {
		return nil, fmt.Errorf("download %s: larger than %d bytes", url, maxFileSize)
	}

	return content, nil
}

// field is one data line of a UCD file: a code point range and its fields.
type field struct {
	lo, hi rune
	values []string
}

// parseRanges reads the "XXXX..YYYY ; value ; value # comment" lines of a
// UCD file.
func parseRanges(content []byte) ([]field, error) {
	var out []field

	scanner := bufio.NewScanner(bytes.NewReader(content))
	for line := 1; scanner.Scan(); line++ {
		text, _, _ := strings.Cut(scanner.Text(), "#")
		if strings.TrimSpace(text) == "" {
			continue
		}

		parts := strings.Split(text, ";")
		for i := range parts {
			parts[i] = strings.TrimSpace(parts[i])
		}

		lo, hi, err := parseRange(parts[0])
		if err != nil {
			return nil, fmt.Errorf("line %d: %w", line, err)
		}

		out = append(out, field{lo: lo, hi: hi, values: parts[1:]})
	}

	if err := scanner.Err(); err != nil {
		return nil, fmt.Errorf("scan: %w", err)
	}

	return out, nil
}

func parseRange(s string) (rune, rune, error) {
	loText, hiText, isRange := strings.Cut(s, "..")

	lo, err := strconv.ParseUint(loText, 16, 32)
	if err != nil {
		return 0, 0, fmt.Errorf("code point %q: %w", loText, err)
	}

	hi := lo
	if isRange {
		hi, err = strconv.ParseUint(hiText, 16, 32)
		if err != nil {
			return 0, 0, fmt.Errorf("code point %q: %w", hiText, err)
		}
	}

	if lo > hi || hi > maxRune {
		return 0, 0, fmt.Errorf("range %q is out of order or past U+10FFFF", s)
	}

	return rune(lo), rune(hi), nil
}

// buildProperties computes the packed properties of every code point.
func buildProperties(data map[string][]byte) ([]uint16, error) {
	eaw := make([]string, maxRune+1)
	for i := range eaw {
		eaw[i] = "N" // # @missing: 0000..10FFFF; N
	}

	if err := forEach(data["EastAsianWidth.txt"], func(f field) {
		for cp := f.lo; cp <= f.hi; cp++ {
			eaw[cp] = f.values[0]
		}
	}); err != nil {
		return nil, fmt.Errorf("EastAsianWidth.txt: %w", err)
	}

	zeroCategory := make([]bool, maxRune+1)
	if err := forEach(data["DerivedGeneralCategory.txt"], func(f field) {
		switch f.values[0] {
		case "Mn", "Me", "Cf":
			for cp := f.lo; cp <= f.hi; cp++ {
				zeroCategory[cp] = true
			}
		}
	}); err != nil {
		return nil, fmt.Errorf("DerivedGeneralCategory.txt: %w", err)
	}

	emojiPresentation := make([]bool, maxRune+1)
	extPict := make([]bool, maxRune+1)

	if err := forEach(data["emoji-data.txt"], func(f field) {
		for cp := f.lo; cp <= f.hi; cp++ {
			switch f.values[0] {
			case "Emoji_Presentation":
				emojiPresentation[cp] = true
			case "Extended_Pictographic":
				extPict[cp] = true
			}
		}
	}); err != nil {
		return nil, fmt.Errorf("emoji-data.txt: %w", err)
	}

	vsBase := make([]bool, maxRune+1)
	if err := parseVariationBases(data["emoji-variation-sequences.txt"], vsBase); err != nil {
		return nil, fmt.Errorf("emoji-variation-sequences.txt: %w", err)
	}

	gcb := make([]uint16, maxRune+1)
	if err := forEach(data["GraphemeBreakProperty.txt"], func(f field) {
		v := indexOf(gcbNames, f.values[0])
		for cp := f.lo; cp <= f.hi; cp++ {
			gcb[cp] = uint16(max(v, 0))
		}
	}); err != nil {
		return nil, fmt.Errorf("GraphemeBreakProperty.txt: %w", err)
	}

	inCB := make([]uint16, maxRune+1)
	if err := forEach(data["DerivedCoreProperties.txt"], func(f field) {
		if f.values[0] != "InCB" || len(f.values) < 2 {
			return
		}

		v := indexOf(inCBNames, f.values[1])
		for cp := f.lo; cp <= f.hi; cp++ {
			inCB[cp] = uint16(max(v, 0))
		}
	}); err != nil {
		return nil, fmt.Errorf("DerivedCoreProperties.txt: %w", err)
	}

	extend := uint16(indexOf(gcbNames, "Extend"))
	zwj := uint16(indexOf(gcbNames, "ZWJ"))
	jamoV := uint16(indexOf(gcbNames, "V"))
	jamoT := uint16(indexOf(gcbNames, "T"))

	props := make([]uint16, maxRune+1)

	for cp := range props {
		width := uint16(propWidthOne)
		if eaw[cp] == "W" || eaw[cp] == "F" || emojiPresentation[cp] {
			width = propWidthWide
		}

		zero := zeroCategory[cp] || gcb[cp] == extend || gcb[cp] == zwj || gcb[cp] == jamoV || gcb[cp] == jamoT
		if zero && !emojiPresentation[cp] && cp != softHyphen {
			width = propWidthZero
		}

		p := width | gcb[cp]<<propGCBShift | inCB[cp]<<propInCBShift
		if extPict[cp] {
			p |= propExtPict
		}

		if vsBase[cp] {
			p |= propVSBase
		}

		props[cp] = p
	}

	return props, nil
}

func forEach(content []byte, fn func(field)) error {
	fields, err := parseRanges(content)
	if err != nil {
		return err
	}

	for _, f := range fields {
		if len(f.values) == 0 {
			return fmt.Errorf("range %04X..%04X has no value", f.lo, f.hi)
		}

		fn(f)
	}

	return nil
}

// parseVariationBases marks the code points that take an emoji or text
// variation selector: "0023 FE0E ; text style; # ..." lines.
func parseVariationBases(content []byte, bases []bool) error {
	scanner := bufio.NewScanner(bytes.NewReader(content))
	for line := 1; scanner.Scan(); line++ {
		text, _, _ := strings.Cut(scanner.Text(), "#")

		sequence, _, found := strings.Cut(text, ";")
		if !found {
			continue
		}

		points := strings.Fields(sequence)
		if len(points) != 2 {
			return fmt.Errorf("line %d: want a base and a selector, got %q", line, sequence)
		}

		cp, err := strconv.ParseUint(points[0], 16, 32)
		if err != nil || cp > maxRune {
			return fmt.Errorf("line %d: code point %q", line, points[0])
		}

		bases[cp] = true
	}

	if err := scanner.Err(); err != nil {
		return fmt.Errorf("scan: %w", err)
	}

	return nil
}

func indexOf(names []string, name string) int {
	for i, n := range names {
		if n == name {
			return i
		}
	}

	return -1
}

// tablesSource renders the properties as ranges of equal values. Code points
// whose properties are those of plain narrow text (width 1, no break class)
// are left out; width.go treats a code point outside every range so.
func tablesSource(props []uint16) []byte {
	var b strings.Builder

	b.WriteString(licenseHeader + generatedLine)
	b.WriteString("package vt\n\n")
	fmt.Fprintf(&b, "// unicodeVersion is the Unicode version the tables were generated from.\nconst unicodeVersion = %q\n\n", unicodeVersion)
	b.WriteString("// unicodeRanges holds the properties of every code point that is not plain\n")
	b.WriteString("// narrow text, as sorted, non-overlapping ranges. See propsOf in width.go\n")
	b.WriteString("// for the bits.\n")
	b.WriteString("var unicodeRanges = [...]propRange{\n")

	plain := uint16(propWidthOne | gcbOther<<propGCBShift | inCBNone<<propInCBShift)
	count := 0

	for cp := 0; cp <= maxRune; {
		p := props[cp]
		end := cp
		for end+1 <= maxRune && props[end+1] == p {
			end++
		}

		if p != plain {
			fmt.Fprintf(&b, "\t{0x%04X, 0x%04X, 0x%03X},\n", cp, end, p)
			count++
		}

		cp = end + 1
	}

	b.WriteString("}\n")
	fmt.Fprintf(os.Stderr, "%s: %d ranges\n", tablesFile, count)

	return []byte(b.String())
}

// breakCase is one line of GraphemeBreakTest.txt: code points and the
// clusters they form.
type breakCase struct {
	clusters [][]rune
	comment  string
}

// parseBreakTest reads "÷ 0020 × 0308 ÷ 0020 ÷ # comment" lines.
func parseBreakTest(content []byte) ([]breakCase, error) {
	var out []breakCase

	scanner := bufio.NewScanner(bytes.NewReader(content))
	for line := 1; scanner.Scan(); line++ {
		text, comment, _ := strings.Cut(scanner.Text(), "#")
		if strings.TrimSpace(text) == "" {
			continue
		}

		var (
			c       breakCase
			current []rune
		)

		for _, token := range strings.Fields(text) {
			switch token {
			case "÷":
				if len(current) > 0 {
					c.clusters = append(c.clusters, current)
					current = nil
				}
			case "×":
			default:
				cp, err := strconv.ParseUint(token, 16, 32)
				if err != nil || cp > maxRune {
					return nil, fmt.Errorf("GraphemeBreakTest.txt line %d: code point %q", line, token)
				}

				current = append(current, rune(cp))
			}
		}

		if len(current) > 0 {
			return nil, fmt.Errorf("GraphemeBreakTest.txt line %d: does not end with ÷", line)
		}

		c.comment = strings.TrimSpace(comment)
		out = append(out, c)
	}

	if err := scanner.Err(); err != nil {
		return nil, fmt.Errorf("scan GraphemeBreakTest.txt: %w", err)
	}

	return out, nil
}

func casesSource(cases []breakCase) []byte {
	var b strings.Builder

	b.WriteString(licenseHeader + generatedLine)
	b.WriteString("package vt\n\n")
	b.WriteString("// graphemeBreakCases are the lines of GraphemeBreakTest.txt: each is a list\n")
	b.WriteString("// of clusters, each cluster a list of code points.\n")
	b.WriteString("var graphemeBreakCases = [...][][]rune{\n")

	for _, c := range cases {
		parts := make([]string, 0, len(c.clusters))
		for _, cluster := range c.clusters {
			points := make([]string, 0, len(cluster))
			for _, cp := range cluster {
				points = append(points, fmt.Sprintf("0x%04X", cp))
			}

			parts = append(parts, "{"+strings.Join(points, ", ")+"}")
		}

		fmt.Fprintf(&b, "\t{%s},\n", strings.Join(parts, ", "))
	}

	b.WriteString("}\n")
	fmt.Fprintf(os.Stderr, "%s: %d cases\n", casesFile, len(cases))

	return []byte(b.String())
}

func writeGo(name string, source []byte) error {
	formatted, err := format.Source(source)
	if err != nil {
		return fmt.Errorf("format %s: %w", name, err)
	}

	// A source file of the package, readable like the others.
	if err := os.WriteFile(name, formatted, 0o644); err != nil { //nolint:gosec // G306: committed source
		return fmt.Errorf("write %s: %w", name, err)
	}

	return nil
}
