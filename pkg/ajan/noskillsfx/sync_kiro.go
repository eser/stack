// The Kiro adapter (sync/adapters/kiro.ts): steering files with inclusion
// frontmatter in .kiro/steering/, the hooks in .kiro/hooks/noskills.json, the
// agents in .kiro/agents/, three files per spec in .kiro/specs/<name>/ and
// the MCP server in .kiro/settings/mcp.json.

const (
	kiroSteeringDir = ".kiro/steering"
	kiroRulesFile   = kiroSteeringDir + "/noskills-rules.md"
	kiroLegacyFile  = kiroSteeringDir + "/conventions.md"
)

func kiroProtocol(c *SyncContext) string {
	lines := append([]string{
		"---",
		"inclusion: always",
		"---",
		"",
		"# noskills Protocol",
		"",
		"# Generated by noskills — do not edit manually",
		"",
	}, protocolLines(c.CommandPrefix, "##", c.Options)...)

	return strings.Join(lines, "\n")
}

func kiroCoaching(prefix string) string {
	lines := append([]string{
		"---",
		"inclusion: auto",
		"name: noskills-coaching",
		`description: "Guidance for noskills spec-driven development workflow, including convention discovery and rule promotion"`,
		"---",
		"",
		"# noskills Coaching",
		"",
		"# Generated by noskills — do not edit manually",
		"",
	}, coachingLines(prefix, "##")...)

	return strings.Join(lines, "\n")
}

func kiroRules(rules []string) string {
	lines := append([]string{
		"---",
		"inclusion: always",
		"---",
		"",
		"# noskills Rules",
		"",
		"# Generated by noskills — do not edit manually",
		"",
		"## Active Rules",
		"",
	}, bulletLines(rules)...)

	return strings.Join(append(lines, ""), "\n")
}

func syncKiroSteering(c *SyncContext) error {
	if err := writeSyncFile(c.path(kiroSteeringDir+"/noskills-protocol.md"), kiroProtocol(c)); err != nil {
		return err
	}

	if err := writeSyncFile(c.path(kiroSteeringDir+"/noskills-coaching.md"), kiroCoaching(c.CommandPrefix)); err != nil {
		return err
	}

	if len(c.Rules) > 0 {
		if err := writeSyncFile(c.path(kiroRulesFile), kiroRules(c.Rules)); err != nil {
			return err
		}
	} else if err := removeIfExists(c.path(kiroRulesFile)); err != nil {
		return err
	}

	return removeIfExists(c.path(kiroLegacyFile))
}

func kiroWriteTools() []string {
	return []string{"write", "fs_write", "fsWrite", "fs_append", "str_replace", "delete_file"}
}

func kiroShellTools() []string {
	return []string{"shell", "execute_bash", "execute_cmd"}
}

func kiroAnyOf(names []string) string {
	return "^(" + strings.Join(names, "|") + ")$"
}

func kiroHook(prefix string, event HookEvent, trigger, description, matcher string) *JSObject {
	hook := JSObjectOf("name", "noskills-"+string(event), "description", description, "trigger", trigger)
	if matcher != "" {
		hook.set("matcher", matcher)
	}

	hook.set("action", JSObjectOf("type", "command", "command", HookCommand(prefix, event)))
	hook.set("timeout", float64(HookTimeoutSeconds(event)))

	return hook
}

func kiroHooksFile(prefix string) *JSObject {
	return JSObjectOf("version", "v1", "hooks", []any{
		kiroHook(prefix, HookSessionStart, "SessionStart",
			"Generated by noskills: gives the agent the current noskills instruction.", ""),
		kiroHook(prefix, HookPreToolUse, "PreToolUse",
			"Generated by noskills: refuses git writes, changes to the noskills settings and file edits the spec's phase does not allow.",
			kiroAnyOf(append(kiroWriteTools(), kiroShellTools()...))),
		kiroHook(prefix, HookPostFileWrite, "PostToolUse",
			"Generated by noskills: logs the files the agent changed.", kiroAnyOf(kiroWriteTools())),
		kiroHook(prefix, HookPostBash, "PostToolUse",
			"Generated by noskills: logs the noskills commands the agent ran.", kiroAnyOf(kiroShellTools())),
		kiroHook(prefix, HookStop, "Stop",
			"Generated by noskills: records the iteration when the agent stops.", ""),
	})
}

func syncKiroHooks(c *SyncContext) error {
	// noskills owns this file; the user's hooks live in files of their own.
	if err := writeSyncFile(c.path(".kiro/hooks/noskills.json"), jsonStringifyIndent(kiroHooksFile(c.CommandPrefix))+"\n"); err != nil {
		return err
	}

	return removeKiroLegacyHooks(c.path(".kiro/settings/hooks.json"))
}

// removeKiroLegacyHooks takes the hooks earlier noskills versions wrote to
// .kiro/settings/hooks.json (marked _noskills) out of it, and removes the
// file when nothing else is left. A missing or non-JSON file stays.
func removeKiroLegacyHooks(path string) error {
	parsed, ok := readJSONFile(path)
	if !ok {
		return nil
	}

	file, isObject := parsed.(*JSObject)
	if !isObject {
		return nil
	}

	hooks, isList := file.getOr("hooks").([]any)
	if !isList {
		return nil
	}

	userHooks := make([]any, 0, len(hooks))

	for _, hook := range hooks {
		// `hook instanceof Object`: arrays count, and their _noskills is
		// undefined.
		if o, isHook := hook.(*JSObject); isHook && o.isTrue("_noskills") {
			continue
		}

		userHooks = append(userHooks, hook)
	}

	if len(userHooks) == len(hooks) {
		return nil
	}

	if len(userHooks) == 0 && len(file.Keys()) == 1 {
		return removeIfExists(path)
	}

	merged := file.clone()
	merged.set("hooks", userHooks)

	return writeSyncFile(path, jsonStringifyIndent(merged)+"\n")
}

func kiroAgent(name, description string, tools, allowed []string, prompt []string) *JSObject {
	return JSObjectOf(
		"name", name,
		"description", description,
		"tools", anyOf(tools),
		"allowedTools", anyOf(allowed),
		"resources", []any{"file://.kiro/steering/noskills-protocol.md"},
		"prompt", strings.Join(prompt, "\n"),
	)
}

func syncKiroAgents(c *SyncContext) error {
	executorTools := []string{"read", "write", "glob", "grep", "shell", "delegate"}
	executor := kiroAgent("noskills-executor",
		"Executes a single noskills task. Follows spec behavioral rules and reports structured results.",
		executorTools, executorTools, executorPromptLines(c.CommandPrefix))

	if err := writeSyncFile(c.path(".kiro/agents/noskills-executor.json"), jsonStringifyIndent(executor)+"\n"); err != nil {
		return err
	}

	verifier := kiroAgent("noskills-verifier",
		"Independently verifies completed task work. Read-only. Never sees the executor's context.",
		[]string{"read", "glob", "grep", "shell", "use_subagent"}, []string{"read", "glob", "grep", "shell"},
		verifierPromptLines())

	return writeSyncFile(c.path(".kiro/agents/noskills-verifier.json"), jsonStringifyIndent(verifier)+"\n")
}

func kiroRequirements(spec *parsedSpec) string {
	overview := spec.discoveryAnswers
	if overview == "" {
		overview = "(no discovery answers yet)"
	}

	lines := []string{"# Feature: " + spec.title, "", "## Overview", "", overview, "", "## Requirements", ""}

	var requirements []string

	for _, line := range strings.Split(spec.discoveryAnswers, "\n") {
		if strings.HasPrefix(line, "### ") {
			requirements = append(requirements, "- "+jsReplaceFirstRegexp(line, mirrorHeadingPrefix, ""))
		}
	}

	switch {
	case len(requirements) > 0:
		lines = append(lines, requirements...)
	case spec.discoveryAnswers != "":
		lines = append(lines, "- See overview for details")
	default:
		lines = append(lines, "- (none yet)")
	}

	lines = append(lines, "", "## Acceptance Criteria", "")

	if spec.verification != "" {
		for _, line := range strings.Split(spec.verification, "\n") {
			if jsTrim(line) == "" {
				continue
			}

			if item := jsTrim(jsReplaceFirstRegexp(line, mirrorBulletPrefix, "")); item != "" {
				lines = append(lines, "- [ ] "+item)
			}
		}
	} else {
		lines = append(lines, "- [ ] (none yet)")
	}

	outOfScope := spec.outOfScope
	if outOfScope == "" {
		outOfScope = "(nothing listed)"
	}

	lines = append(lines, "", "## Out of Scope", "", outOfScope, "")

	return strings.Join(lines, "\n")
}

func kiroDesign(spec *parsedSpec) string {
	lines := []string{"# Design: " + spec.title, "", "## Architecture", ""}

	if spec.discoveryAnswers != "" {
		lines = append(lines, spec.discoveryAnswers)
	} else {
		lines = append(lines, "(no architecture decisions yet)")
	}

	lines = append(lines, "", "## Concerns", "")

	if spec.concerns != "" {
		lines = append(lines, spec.concerns)
	} else {
		lines = append(lines, "(no active concerns)")
	}

	lines = append(lines, "", "## Decisions", "")

	if spec.contributorGuide != "" || spec.publicAPI != "" {
		if spec.contributorGuide != "" {
			lines = append(lines, "### Contributor Guide", "", spec.contributorGuide, "")
		}

		if spec.publicAPI != "" {
			lines = append(lines, "### Public API Surface", "", spec.publicAPI, "")
		}
	} else {
		lines = append(lines, "(no decisions yet)")
	}

	return strings.Join(append(lines, ""), "\n")
}

func kiroTasks(spec *parsedSpec) string {
	tasks := spec.tasks
	if tasks == "" {
		tasks = "(no tasks yet)"
	}

	return strings.Join([]string{"# Tasks: " + spec.title, "", tasks, ""}, "\n")
}

func syncKiroSpec(c *SyncContext, specName, specPath string) error {
	spec, ok := readSpecMirror(specPath)
	if !ok {
		return nil
	}

	dir := ".kiro/specs/" + specName

	if err := writeSyncFile(c.path(dir+"/requirements.md"), kiroRequirements(spec)); err != nil {
		return err
	}

	if err := writeSyncFile(c.path(dir+"/design.md"), kiroDesign(spec)); err != nil {
		return err
	}

	return writeSyncFile(c.path(dir+"/tasks.md"), kiroTasks(spec))
}

func syncKiroMcp(c *SyncContext) error {
	path := c.path(".kiro/settings/mcp.json")

	if err := os.MkdirAll(c.path(".kiro/settings"), 0o750); err != nil {
		return err //nolint:wrapcheck // the message names the folder
	}

	parts := splitCommandPrefix(c.CommandPrefix)
	server := JSObjectOf(
		"command", parts[0],
		"args", anyOf(append(parts[1:len(parts):len(parts)], "mcp-serve")),
		"env", NewJSObject(),
		"autoApprove", []any{"noskills_next", "noskills_status"},
		"disabled", false,
	)

	merged := withNoskillsServer(mcpServersConfig(path), "mcpServers", server)

	return writeSyncFile(path, jsonStringifyIndent(merged)+"\n")
}
