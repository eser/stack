// The OpenCode adapter (sync/adapters/opencode.ts): AGENTS.md, the plugin
// .opencode/plugins/noskills.ts that runs the hooks, the agents in
// .opencode/agents/, a skill per spec in .opencode/skills/ and the MCP
// server in opencode.json.

// opencodePlugin is buildPluginContent: the plugin passes each guarded tool
// call to `invoke-hook pre-tool-use` and refuses it when noskills refuses it
// or does not answer in time.
func opencodePlugin(prefix string) string {
	seconds := func(event HookEvent) string { return strconv.Itoa(HookTimeoutSeconds(event)) }

	return `// Generated by noskills. Do not edit by hand: ` + "`noskills init`" + ` rewrites it.
//
// Runs the noskills hooks in OpenCode (opencode.ai/docs/plugins). Before a
// shell or file tool runs, the call goes to ` + "`invoke-hook pre-tool-use`" + ` on
// stdin, and the tool call is refused when noskills refuses it or does not
// answer in time.
import { spawn } from "node:child_process";
import process from "node:process";

const COMMAND = ` + jsonStringify(prefix) + `;

// Seconds each hook may take.
const TIMEOUT_SECONDS: Record<string, number> = {
  "session-start": ` + seconds(HookSessionStart) + `,
  "pre-tool-use": ` + seconds(HookPreToolUse) + `,
  "post-file-write": ` + seconds(HookPostFileWrite) + `,
  "post-bash": ` + seconds(HookPostBash) + `,
  stop: ` + seconds(HookStop) + `,
};
` + opencodePluginBody
}

// opencodePluginBody is the part of the plugin that does not depend on the
// project.
const opencodePluginBody = `
// OpenCode's shell tool and the tools that write files (opencode.ai/docs/tools).
const SHELL_TOOLS = new Set(["bash"]);
const FILE_TOOLS = new Set(["edit", "write", "apply_patch"]);

// Exit code with which invoke-hook refuses a tool call.
const DENIED = 2;

type HookResult = {
  readonly status: number | null;
  readonly stderr: string;
  readonly failure: string | null;
};

const runHook = (
  directory: string,
  event: string,
  payload: unknown,
): Promise<HookResult> =>
  new Promise((resolve) => {
    const seconds = TIMEOUT_SECONDS[event] ?? 10;
    const child = spawn(` + "`${COMMAND} invoke-hook ${event}`" + `, {
      shell: true,
      cwd: directory,
      env: { ...process.env, NOSKILLS_PROJECT_ROOT: directory },
      stdio: ["pipe", "ignore", "pipe"],
    });

    let stderr = "";
    let settled = false;
    // Called from the timer and the child's events, which come after timer
    // is set.
    const settle = (result: HookResult): void => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      resolve(result);
    };
    const timer = setTimeout(() => {
      child.kill();
      settle({
        status: null,
        stderr,
        failure: ` + "`did not answer within ${seconds} seconds`" + `,
      });
    }, seconds * 1000);

    child.stderr?.on("data", (chunk: unknown) => {
      stderr += String(chunk);
    });
    child.on("error", (error: Error) => {
      settle({ status: null, stderr, failure: error.message });
    });
    child.on("close", (status: number | null) => {
      settle({ status, stderr, failure: null });
    });
    // The hook may exit before it reads its input.
    child.stdin?.on("error", () => {});
    child.stdin?.end(JSON.stringify(payload));
  });

const guard = async (
  directory: string,
  tool: string,
  sessionID: string,
  args: unknown,
): Promise<void> => {
  const result = await runHook(directory, "pre-tool-use", {
    hook_event_name: "PreToolUse",
    session_id: sessionID,
    cwd: directory,
    tool_name: tool,
    tool_input: args,
  });

  if (result.status === 0) return;
  if (result.status === DENIED) {
    throw new Error(result.stderr.trim() || "noskills refused this tool call.");
  }

  const cause = result.failure ??
    ` + "`exited with code ${result.status}: ${result.stderr.trim()}`" + `;
  throw new Error(
    ` + "`noskills: the PreToolUse check ${cause}, so this call was refused. When command in .eser/manifest.yml starts noskills through npx, install noskills and run its init again, so the check does not wait on the network.`" + `,
  );
};

const hooksFor = (directory: string) => ({
  event: async ({ event }: { event: { type: string } }) => {
    if (event.type === "session.created") {
      await runHook(directory, "session-start", {});
    } else if (event.type === "session.idle") {
      await runHook(directory, "stop", {
        hook_event_name: "Stop",
        cwd: directory,
      });
    }
  },
  "tool.execute.before": async (
    input: { tool: string; sessionID: string },
    output: { args: unknown },
  ) => {
    if (SHELL_TOOLS.has(input.tool) || FILE_TOOLS.has(input.tool)) {
      await guard(directory, input.tool, input.sessionID, output.args);
    }
  },
  "tool.execute.after": async (
    input: { tool: string; sessionID: string; args: unknown },
  ) => {
    const event = FILE_TOOLS.has(input.tool)
      ? "post-file-write"
      : SHELL_TOOLS.has(input.tool)
      ? "post-bash"
      : null;
    if (event === null) return;

    await runHook(directory, event, {
      hook_event_name: "PostToolUse",
      session_id: input.sessionID,
      cwd: directory,
      tool_name: input.tool,
      tool_input: input.args,
    });
  },
});

export const NoskillsPlugin = ({ directory }: { directory: string }) =>
  Promise.resolve(hooksFor(directory));
`

func syncOpencodePlugin(c *SyncContext) error {
	return writeSyncFile(c.path(".opencode/plugins/noskills.ts"), opencodePlugin(c.CommandPrefix))
}

func syncOpencodeAgents(c *SyncContext) error {
	executor := markdownAgent([]string{
		"name: noskills-executor",
		`description: "Executes a single noskills task. Follows spec behavioral rules and reports structured results."`,
		"tools:", "  read: true", "  write: true", "  glob: true", "  grep: true", "  shell: true", "  delegate: true",
	}, executorPromptLines(c.CommandPrefix))

	if err := writeSyncFile(c.path(".opencode/agents/noskills-executor.md"), executor); err != nil {
		return err
	}

	verifier := markdownAgent([]string{
		"name: noskills-verifier",
		`description: "Independently verifies completed task work. Read-only. Never sees the executor's context."`,
		"tools:", "  read: true", "  glob: true", "  grep: true", "  shell: true",
	}, verifierPromptLines())

	return writeSyncFile(c.path(".opencode/agents/noskills-verifier.md"), verifier)
}

func opencodeSkill(spec *parsedSpec) string {
	lines := []string{
		"---",
		"name: " + spec.title,
		`description: "noskills spec: ` + spec.title + `"`,
		"---",
		"",
		"# " + spec.title,
		"",
	}

	for _, section := range []struct{ heading, body string }{
		{"Overview", spec.discoveryAnswers},
		{"Concerns", spec.concerns},
		{"Contributor Guide", spec.contributorGuide},
		{"Public API", spec.publicAPI},
		{"Out of Scope", spec.outOfScope},
		{"Tasks", spec.tasks},
		{"Verification", spec.verification},
	} {
		if section.body != "" {
			lines = append(lines, "## "+section.heading, "", section.body, "")
		}
	}

	return strings.Join(lines, "\n")
}

func syncOpencodeSkill(c *SyncContext, specName, specPath string) error {
	spec, ok := readSpecMirror(specPath)
	if !ok {
		return nil
	}

	return writeSyncFile(c.path(".opencode/skills/"+specName+".md"), opencodeSkill(spec))
}

// syncOpencodeMcp registers the MCP server in opencode.json and keeps the
// rest of the config. A file that is not JSON starts from an empty config;
// JSON null does too (the TypeScript adapter throws on it).
func syncOpencodeMcp(c *SyncContext) error {
	path := c.path("opencode.json")

	existing, ok := readJSONFile(path)
	if !ok {
		existing = NewJSObject()
	}

	var mcp any
	if o, isObject := existing.(*JSObject); isObject {
		mcp = o.getOr("mcp")
	}

	command := append(splitCommandPrefix(c.CommandPrefix), "mcp-serve")

	servers := jsSpread(mcp)
	servers.set("noskills", JSObjectOf("type", "local", "command", anyOf(command), "enabled", true))

	merged := jsSpread(existing)
	merged.set("mcp", servers)

	return writeSyncFile(path, jsonStringifyIndent(merged)+"\n")
}
