package noskillsfx

import "strings"

// The one rule file of Cursor, Windsurf and GitHub Copilot
// (sync/rule-file.ts): those tools read a single instruction file and run no
// noskills hooks, so their files differ only in where they are written.

const (
	cursorRuleFile   = ".cursorrules"
	windsurfRuleFile = ".windsurfrules"
	copilotRuleFile  = ".github/copilot-instructions.md"
)

// buildRuleFile is buildRuleFile: every command starts with the prefix, and
// every command that works on a spec carries `spec <name>`.
func buildRuleFile(rules []string, prefix string) string {
	specNext := prefix + " spec <name> next"
	lines := []string{
		"# Generated by noskills — do not edit manually",
		"",
		"## noskills orchestrator",
		"",
		"This project uses noskills for state-driven orchestration.",
		"Do NOT read `.eser/specs/` or `.eser/rules/` directly. noskills gives you what you need.",
		"",
		"Run `" + specNext + "` to get your current instruction.",
		"Submit results with `" + specNext + ` --answer="..."` + "`.",
		"",
		"Every noskills command that works on a spec MUST include `spec <name>`; noskills refuses it without the name while a spec is active.",
		"Use `" + prefix + " spec list` to see the specs. With no spec yet, run `" + prefix + " next`, or create one with `" +
			prefix + ` spec new "description"` + "`.",
		"",
		"## Why noskills calls matter",
		"",
		"noskills is not a form to fill out. It is a live state machine that the user",
		"watches in real-time. Every `" + specNext + " --answer` call:",
		"",
		"- Updates the spec file on disk (the user sees it change)",
		"- Updates the terminal dashboard if `" + prefix + " watch` is running",
		"- Advances the state machine to the next phase",
		"- Records the decision permanently in the project history",
		"",
		discoveryQuestionRule(),
		"Do not answer discovery questions yourself: the user's input is the data.",
		discoveryAnswerRule(specNext + " --answer"),
		"",
		"## When to call noskills next",
		"",
		"1. At the START of every conversation",
		"2. BEFORE creating or modifying any file",
		"3. AFTER completing a logical unit of work",
		"4. When you encounter a DECISION that affects architecture",
		"5. When you are UNSURE what to do next",
		"",
		"NEVER proceed with implementation without checking noskills first.",
		"NEVER suggest bypassing or skipping noskills. Discovery is not overhead.",
		"Run the next noskills command as soon as the current step is done; each step has exactly one next step, so there is nothing to ask permission for.",
		"",
		"## Interactive choices",
		"",
		"Present choices as numbered lists. Users select by number.",
		"When interactiveOptions are present in noskills output, present each as a",
		"numbered item with its label and description. Ask the user to pick a number.",
		"",
		"## Execution model",
		"",
		"Execute tasks sequentially in this context. Do not attempt to spawn sub-agents.",
		"",
	}

	if len(rules) > 0 {
		lines = append(lines, "## Rules", "")
		lines = append(lines, bulletLines(rules)...)
		lines = append(lines, "")
	}

	return strings.Join(lines, "\n")
}

// ruleFileSync writes the rule file to rel, replacing whatever it held.
func ruleFileSync(rel string) func(c *SyncContext) error {
	return func(c *SyncContext) error {
		return writeSyncFile(c.path(rel), buildRuleFile(c.Rules, c.CommandPrefix))
	}
}
